"""
GAT Dataset Loader for PyTorch Geometric

Loads training data generated by Godot's data_generator.gd
and converts it to PyTorch Geometric Data objects.

Usage:
    from gat_dataset import MCTSDataset
    dataset = MCTSDataset("path/to/training_data")
    loader = DataLoader(dataset, batch_size=32, shuffle=True)
"""

import json
import os
from pathlib import Path
from typing import List, Optional, Tuple

import torch
from torch.utils.data import Dataset
from torch_geometric.data import Data, InMemoryDataset


class MCTSDataset(InMemoryDataset):
    """
    PyTorch Geometric dataset for MCTS-generated training data.

    Each sample contains:
        - x: Node features [4, 11] (Tank, Healer, Sniper, Boss)
        - edge_index: Graph connectivity [2, num_edges]
        - edge_attr: Edge features [num_edges, 6]
        - y: Action label (0-9)
        - agent_idx: Which agent is acting (0=Tank, 1=Healer, 2=Sniper)
        - legal_mask: Binary mask of legal actions [10]
    """

    def __init__(self, root: str, transform=None, pre_transform=None):
        super().__init__(root, transform, pre_transform)
        self.data, self.slices = torch.load(self.processed_paths[0])

        # Load metadata
        meta_path = os.path.join(root, "metadata.json")
        if os.path.exists(meta_path):
            with open(meta_path, "r") as f:
                self.metadata = json.load(f)
        else:
            self.metadata = {}

    @property
    def raw_file_names(self) -> List[str]:
        # Find all data_*.json files
        data_dir = self.root
        files = [f for f in os.listdir(data_dir) if f.startswith("data_") and f.endswith(".json")]
        return sorted(files) if files else ["data_0000.json"]

    @property
    def processed_file_names(self) -> List[str]:
        return ["processed_data.pt"]

    def download(self):
        pass  # Data is generated by Godot

    def process(self):
        data_list = []

        for filename in self.raw_file_names:
            filepath = os.path.join(self.root, filename)
            if not os.path.exists(filepath):
                continue

            print(f"Processing {filename}...")
            with open(filepath, "r") as f:
                samples = json.load(f)

            for sample in samples:
                data = self._sample_to_data(sample)
                data_list.append(data)

        print(f"Total samples: {len(data_list)}")

        if self.pre_transform is not None:
            data_list = [self.pre_transform(d) for d in data_list]

        data, slices = self.collate(data_list)
        torch.save((data, slices), self.processed_paths[0])

    def _sample_to_data(self, sample: dict) -> Data:
        """Convert a single sample dict to PyG Data object."""

        # Node features [4, 11]
        x = torch.tensor(sample["node_features"], dtype=torch.float)

        # Edge index [2, num_edges]
        edge_index = torch.tensor(sample["edge_index"], dtype=torch.long)

        # Edge attributes [num_edges, 6]
        edge_attr = torch.tensor(sample["edge_attr"], dtype=torch.float) if sample["edge_attr"] else torch.zeros((0, 6))

        # Action label
        y = torch.tensor(sample["action_id"], dtype=torch.long)

        # Agent index (for agent-specific action heads)
        agent_idx = torch.tensor(sample["agent_idx"], dtype=torch.long)

        # Legal action mask
        legal_mask = torch.tensor(sample["legal_mask"], dtype=torch.float)

        # Target index (for healer actions)
        target_idx = torch.tensor(sample.get("target_idx", -1), dtype=torch.long)

        # Flat features (alternative input)
        flat_features = torch.tensor(sample.get("flat_features", []), dtype=torch.float)

        return Data(
            x=x,
            edge_index=edge_index,
            edge_attr=edge_attr,
            y=y,
            agent_idx=agent_idx,
            legal_mask=legal_mask,
            target_idx=target_idx,
            flat_features=flat_features
        )


class MCTSDatasetSimple(Dataset):
    """
    Simple PyTorch Dataset (not PyG) for flat feature vectors.
    Use this if you want to try non-graph models first.
    """

    def __init__(self, data_dir: str):
        self.samples = []
        self.metadata = {}

        # Load metadata
        meta_path = os.path.join(data_dir, "metadata.json")
        if os.path.exists(meta_path):
            with open(meta_path, "r") as f:
                self.metadata = json.load(f)

        # Load all data files
        for filename in sorted(os.listdir(data_dir)):
            if filename.startswith("data_") and filename.endswith(".json"):
                filepath = os.path.join(data_dir, filename)
                with open(filepath, "r") as f:
                    self.samples.extend(json.load(f))

        print(f"Loaded {len(self.samples)} samples")

    def __len__(self):
        return len(self.samples)

    def __getitem__(self, idx) -> Tuple[torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor]:
        sample = self.samples[idx]

        # Flat features
        features = torch.tensor(sample["flat_features"], dtype=torch.float)

        # Action label
        action = torch.tensor(sample["action_id"], dtype=torch.long)

        # Agent index
        agent_idx = torch.tensor(sample["agent_idx"], dtype=torch.long)

        # Legal mask
        legal_mask = torch.tensor(sample["legal_mask"], dtype=torch.float)

        return features, action, agent_idx, legal_mask


def load_metadata(data_dir: str) -> dict:
    """Load just the metadata file."""
    meta_path = os.path.join(data_dir, "metadata.json")
    with open(meta_path, "r") as f:
        return json.load(f)


def get_action_name(action_id: int) -> str:
    """Convert action ID to name."""
    actions = ["wait", "melee", "taunt", "defensive",
               "heal", "shield", "restore",
               "shot", "cripple", "power"]
    return actions[action_id] if action_id < len(actions) else "unknown"


def get_agent_name(agent_idx: int) -> str:
    """Convert agent index to name."""
    agents = ["tank", "healer", "sniper"]
    return agents[agent_idx] if agent_idx < len(agents) else "unknown"


